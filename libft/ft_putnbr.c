#include "libft.h"

int	ft_putnbr(long n)
{
	char	c;
	int		ret;

	ret = 0;
	if (n < 0)
	{
		ret += write(1, "-", 1);
		n = n * -1;
	}
	if (n >= 10)
		ret += ft_putnbr((n / 10));
	c = '0' + (n % 10);
	ret += write(1, &c, 1);
	return (ret);
}
